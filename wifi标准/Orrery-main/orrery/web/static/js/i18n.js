const conds = (assignment) => (assignment || [])
  .filter(r => r.from === 'condition').map(r => `${r.axis}.${r.subtype}`)
const verdicts = (v) => Object.entries(v || {}).map(([g, x]) => `${g}=${x}`).join(', ')

